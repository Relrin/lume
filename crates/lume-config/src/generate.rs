//! The files that are made from this crate's definitions and kept in the repository.
//!
//! Editors complete from the JSON Schemas, and the page's code is typed against the
//! token set, so both are files that other tools read. They are generated here, written
//! by a build command, and held equal to what the code generates by a test: a change to
//! a setting or a token that is not followed by generating again fails the test.

pub use lume_codegen::{Generated, GeneratedKind, pretty_json};

use std::collections::BTreeMap;

use lume_codegen::ts::Options;
use schemars::generate::SchemaSettings;
use serde_json::Value;

use crate::schema::config_schema;
use crate::theme::{default_tokens, light_tokens, theme_schema};
use crate::tokens::typescript;

/// Where the page's copy of the configuration view's type goes.
pub const VIEW_TYPES_PATH: &str = "packages/ui/src/wire/config.generated.ts";

/// The schemas of the configuration view and of every type it names, by name, as serde
/// writes them.
fn view_definitions() -> BTreeMap<String, Value> {
    let mut settings = SchemaSettings::draft2020_12().for_serialize();
    settings.inline_subschemas = false;
    let mut generator = settings.into_generator();
    generator.subschema_for::<crate::view::ConfigView>();
    let mut definitions: BTreeMap<String, Value> =
        generator.take_definitions(true).into_iter().collect();
    // What a plugin brings is named `<plugin>/<name>`, which TypeScript can say exactly.
    if let Some(Value::Object(contributed)) = definitions.get_mut("Contributed") {
        contributed.insert("x-ts".to_owned(), Value::from("`${string}/${string}`"));
    }
    definitions
}

/// The page's copy of the configuration view's type, as TypeScript.
pub fn view_typescript() -> Result<String, String> {
    let mut out = String::from(
        "// Generated by `cargo xtask types` from crates/lume-config.
         // Do not edit: change the Rust types and generate again.
         
         import type { Tokens } from \"@lume/tokens\";
         
",
    );
    let defaults = serde_json::to_string_pretty(&crate::schema::Config::default())
        .map_err(|error| error.to_string())?;
    out.push_str(&format!(
        "/** Every setting at its default: what the core resolves when no file says otherwise. */
         export const DEFAULT_CONFIG: Config = {defaults};

"
    ));
    for (name, schema) in view_definitions() {
        out.push_str(
            &Options::PAGE
                .declaration(&name, &schema)
                .map_err(|error| format!("{name}: {error}"))?,
        );
        out.push('\n');
    }
    let end = out.trim_end().len();
    out.truncate(end);
    out.push('\n');
    Ok(out)
}

/// Every generated file, with the text it should have.
pub fn generated_files() -> Vec<Generated> {
    let defaults = default_tokens();
    vec![
        Generated {
            kind: GeneratedKind::Schema,
            path: "schemas/config.schema.json",
            text: pretty_json(config_schema()),
        },
        Generated {
            kind: GeneratedKind::Schema,
            path: "schemas/theme.schema.json",
            text: pretty_json(&theme_schema()),
        },
        Generated {
            kind: GeneratedKind::Tokens,
            path: "packages/tokens/src/generated.ts",
            text: typescript(&defaults, &light_tokens()),
        },
        Generated {
            kind: GeneratedKind::Tokens,
            path: "packages/tokens/src/defaults.css",
            text: defaults.css(),
        },
        Generated {
            kind: GeneratedKind::Types,
            path: VIEW_TYPES_PATH,
            text: view_typescript().unwrap_or_else(|error| {
                format!(
                    "// could not be generated: {error}
"
                )
            }),
        },
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn there_is_a_schema_for_the_settings_and_for_themes_and_the_token_files() {
        let files = generated_files();
        let paths: Vec<&str> = files.iter().map(|file| file.path).collect();
        assert_eq!(
            paths,
            [
                "schemas/config.schema.json",
                "schemas/theme.schema.json",
                "packages/tokens/src/generated.ts",
                "packages/tokens/src/defaults.css",
                "packages/ui/src/wire/config.generated.ts",
            ]
        );
        for file in &files {
            assert!(file.text.ends_with('\n'), "{}", file.path);
            assert!(!file.text.contains('\r'), "{}", file.path);
        }
        assert!(files[2].text.contains("export const TOKEN_KINDS = {"));
        assert!(files[3].text.contains("--lume-color-surface: #121416;"));
    }

    #[test]
    fn the_view_a_page_is_told_can_be_said_in_typescript() {
        let text = view_typescript().unwrap();
        for wanted in [
            "import type { Tokens } from \"@lume/tokens\";",
            "export interface ConfigView {",
            "readonly tokens: Tokens;",
            "readonly \"copy-on-select\": boolean;",
        ] {
            assert!(text.contains(wanted), "missing {wanted:?}");
        }
    }
}
