//! The page's copy of the layout's types, made from the definitions here.
//!
//! A page keeps a copy of the layout and asks for changes by sending intents, so it
//! needs the layout's JSON as TypeScript types. They are generated from the Rust types'
//! JSON Schemas and kept in the repository, and a test holds the file equal to what
//! this generates: a field added here that is not generated again fails the tests
//! instead of being missed by the page.
//!
//! What the core writes (the workspace, its changes) is described as serde writes it.
//! What the core reads (an intent and its parts) is described as serde reads it: a
//! field with a default may be left out, and `null` may be sent to take a value away.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use lume_codegen::ts::Options;
use lume_codegen::{Generated, GeneratedKind};
use lume_proto::{Launcher, TermSize};
use schemars::generate::SchemaSettings;
use serde_json::Value;

use crate::tuning::{FLOAT_CASCADE, FLOAT_DEFAULT, FLOAT_MIN, SHARE_MIN, UNITS};
use crate::{
    Created, GroupIcon, Intent, LayoutChange, Pane, SpawnRequest, Split, TabColor, TerminalPane,
    Workspace,
};

/// Where the page's copy of the types goes, from the root of the repository.
pub const TYPES_PATH: &str = "packages/ui/src/wire/layout.generated.ts";

/// The types only the core reads.
const INPUTS: [&str; 6] = [
    "Intent",
    "NewContent",
    "SpawnRequest",
    "Place",
    "FocusTarget",
    "TabTarget",
];

/// The schemas of the layout's types, by name.
pub fn definitions() -> BTreeMap<String, Value> {
    let mut settings = SchemaSettings::draft2020_12().for_serialize();
    settings.inline_subschemas = false;
    let mut generator = settings.into_generator();
    generator.subschema_for::<Workspace>();
    generator.subschema_for::<Intent>();
    generator.subschema_for::<LayoutChange>();
    generator.subschema_for::<Created>();
    // Named on their own as well as where a tagged union takes their fields in, so the
    // page can name them.
    generator.subschema_for::<Split>();
    generator.subschema_for::<Pane>();
    generator.subschema_for::<TerminalPane>();
    generator.subschema_for::<SpawnRequest>();
    generator.subschema_for::<Launcher>();
    generator.subschema_for::<TermSize>();
    let mut definitions: BTreeMap<String, Value> =
        generator.take_definitions(true).into_iter().collect();
    for name in INPUTS {
        if let Some(schema) = definitions.get_mut(name) {
            as_read(schema);
        }
    }
    definitions
}

/// Changes a schema made as serde writes a type into one as serde reads it: a field
/// with a default need not be given.
fn as_read(schema: &mut Value) {
    let Value::Object(object) = schema else {
        return;
    };
    let defaulted: Vec<String> = object
        .get("properties")
        .and_then(Value::as_object)
        .map(|properties| {
            properties
                .iter()
                .filter(|(_, property)| property.get("default").is_some())
                .map(|(name, _)| name.clone())
                .collect()
        })
        .unwrap_or_default();
    if let Some(Value::Array(required)) = object.get_mut("required") {
        required.retain(|name| {
            name.as_str()
                .is_none_or(|name| !defaulted.iter().any(|given| given == name))
        });
    }
    for key in ["oneOf", "anyOf", "allOf"] {
        if let Some(Value::Array(parts)) = object.get_mut(key) {
            parts.iter_mut().for_each(as_read);
        }
    }
}

/// The page's copy of the layout's types, as TypeScript.
pub fn typescript() -> Result<String, String> {
    let mut out = String::from(
        "// Generated by `cargo xtask types` from crates/lume-layout and crates/lume-proto.\n\
         // Do not edit: change the Rust types and generate again.\n\
         \n",
    );
    let constants: [(&str, u32, &str); 5] = [
        (
            "UNITS",
            UNITS,
            "What a whole is divided into: a split's ratios add up to exactly this.",
        ),
        (
            "SHARE_MIN",
            SHARE_MIN,
            "The smallest share of a split one of its children may have.",
        ),
        (
            "FLOAT_MIN",
            FLOAT_MIN,
            "The smallest a floating pane may be along either side, in units.",
        ),
        (
            "FLOAT_DEFAULT",
            FLOAT_DEFAULT,
            "The side of a pane that floats without being told where, in units.",
        ),
        (
            "FLOAT_CASCADE",
            FLOAT_CASCADE,
            "How far each further pane floated without a place is moved from the one before.",
        ),
    ];
    for (name, value, doc) in constants {
        let _ = writeln!(out, "/** {doc} */\nexport const {name} = {value};\n");
    }
    let colors: Vec<String> = TabColor::NAMED
        .iter()
        .map(|(_, word)| format!("  {},\n", Value::from(*word)))
        .collect();
    let _ = writeln!(
        out,
        "/** Every named colour, in the order a tab's menu offers them. */\n\
         export const TAB_COLORS: readonly NamedTabColor[] = [\n{}];\n",
        colors.concat()
    );
    let icons: Vec<String> = GroupIcon::ALL
        .iter()
        .map(|icon| format!("  {},\n", serde_json::to_value(icon).unwrap_or_default()))
        .collect();
    let _ = writeln!(
        out,
        "/** Every group picture, in the order the group editor offers them. */\n\
         export const GROUP_ICONS: readonly GroupIcon[] = [\n{}];\n",
        icons.concat()
    );
    for (name, schema) in definitions() {
        let options = if INPUTS.contains(&name.as_str()) {
            Options::PAGE_INPUT
        } else {
            Options::PAGE
        };
        out.push_str(
            &options
                .declaration(&name, &schema)
                .map_err(|error| format!("{name}: {error}"))?,
        );
        out.push('\n');
    }
    let end = out.trim_end().len();
    out.truncate(end);
    out.push('\n');
    Ok(out)
}

/// Every file this crate generates.
pub fn generated_files() -> Vec<Generated> {
    vec![Generated {
        kind: GeneratedKind::Types,
        path: TYPES_PATH,
        text: typescript().unwrap_or_else(|error| format!("// could not be generated: {error}\n")),
    }]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_types_can_be_said_in_typescript() {
        let text = typescript().unwrap();
        for wanted in [
            "export interface Workspace {",
            "export type Intent =",
            "export type LayoutChange =",
            "export type TabColor = NamedTabColor | `#${string}`;",
            "export const UNITS = 1000000;",
            "readonly env: readonly (readonly [string, string])[];",
        ] {
            assert!(text.contains(wanted), "missing {wanted:?}");
        }
    }

    #[test]
    fn a_field_with_a_default_need_not_be_given_in_what_is_read() {
        let definitions = definitions();
        let intent = &definitions["Intent"];
        let rename = intent["oneOf"]
            .as_array()
            .unwrap()
            .iter()
            .find(|variant| variant["properties"]["type"]["const"] == "pane_rename")
            .unwrap();
        assert_eq!(rename["required"], serde_json::json!(["type", "pane"]));
        // What is written keeps every field it always writes.
        assert!(
            definitions["Tab"]["required"]
                .as_array()
                .unwrap()
                .contains(&Value::from("title"))
        );
    }
}
